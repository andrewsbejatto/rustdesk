// Strings of the TRMM screens (pt-BR / en). Language follows the TRMM user
// setting (dashinfo "default_lang"/"language"), falling back to the OS locale.

import 'dart:io';

String _lang = Platform.localeName.toLowerCase().startsWith('pt') ? 'pt' : 'en';

void setTrmmLanguage(String code) {
  if (code.isEmpty) return;
  _lang = code.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

/// translate; {0}, {1}... are replaced by [args]
String tr(String key, [List<Object?> args = const []]) {
  var s = (_lang == 'pt' ? _pt[key] : _en[key]) ?? key;
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

